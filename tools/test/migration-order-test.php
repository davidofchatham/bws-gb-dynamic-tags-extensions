$failures = 0;
$count    = 0;

function assert_eq( string $label, $expected, $actual ): void {
	global $failures, $count;
	$count++;
	if ( $expected === $actual ) {
		echo "  ok   {$label}\n";
		return;
	}
	$failures++;
	echo "  FAIL {$label}\n";
	echo "       expected: " . var_export( $expected, true ) . "\n";
	echo "       actual:   " . var_export( $actual, true ) . "\n";
}

// Two try-capable templates stand in for the plugin's real set: the registration pass derives
// its try_ and term_ entries from get_modifier_templates(), so without any there is no family
// to order. Two is enough to show the loops are per-tag rather than per-run.
TagTemplateRegistry::register_modifier_template( array( 'key' => 'text', 'supports_try' => true ) );
TagTemplateRegistry::register_modifier_template( array( 'key' => 'image', 'supports_try' => true ) );

bws_register_option_migrations();

/**
 * Which role an option entry plays, or '' when it is none of the ordered ones.
 *
 * A role is a transform_callback name, except the try_ slot-key rename, which is
 * declarative and is recognized by the legacy `src_1` key it matches on.
 */
function entry_role( array $e ): string {
	$cb = $e['transform_callback'] ?? '';
	if ( is_string( $cb ) && '' !== $cb ) {
		$by_callback = array(
			'bws_migrate_rel_to_ref'            => 'rel_to_ref',
			'bws_migrate_related_post_src'      => 'related_src',
			'bws_migrate_image_as_size_fold'    => 'size_fold',
			'bws_migrate_image_as_bare_url'     => 'bare_url',
			'bws_migrate_base_src_chain'        => 'base_chain',
			'bws_migrate_join_format_escape'    => 'join_escape',
			'bws_migrate_src_chain_slots'       => 'slot_fold',
		);
		return $by_callback[ $cb ] ?? '';
	}
	if ( in_array( 'src_1', $e['match_any_options'] ?? array(), true ) ) {
		return 'slot_rename';
	}
	return '';
}

/**
 * Violations of "A registers before B" over a map of tag => entries.
 *
 * @param array<string,array[]> $by_tag
 * @return array{checked:string[],violations:string[]} Tags where both roles exist, and those that broke the order.
 */
function check_before( array $by_tag, string $a, string $b ): array {
	$checked    = array();
	$violations = array();
	foreach ( $by_tag as $tag => $entries ) {
		$roles = array_map( 'entry_role', $entries );
		$ia    = array_keys( $roles, $a, true );
		$ib    = array_keys( $roles, $b, true );
		if ( ! $ia || ! $ib ) {
			continue;
		}
		$checked[] = $tag;
		// Every A before every B, so a second copy of a role registered late is seen too.
		if ( max( $ia ) > min( $ib ) ) {
			$violations[] = $tag;
		}
	}
	return array( 'checked' => $checked, 'violations' => $violations );
}

/**
 * Violations of "this role registers LAST among its tag's entries".
 *
 * @param array<string,array[]> $by_tag
 * @return array{checked:string[],violations:string[]}
 */
function check_last( array $by_tag, string $role ): array {
	$checked    = array();
	$violations = array();
	foreach ( $by_tag as $tag => $entries ) {
		$roles = array_map( 'entry_role', $entries );
		if ( ! in_array( $role, $roles, true ) ) {
			continue;
		}
		$checked[] = $tag;
		if ( end( $roles ) !== $role ) {
			$violations[] = $tag;
		}
	}
	return array( 'checked' => $checked, 'violations' => $violations );
}

$by_tag = MigrationRegistry::get_option_migrations_by_tag();

// ===========================================================================
echo "O1 — every ordered role is registered at least once (vacuity guard)\n";

$present = array();
foreach ( $by_tag as $entries ) {
	foreach ( $entries as $e ) {
		$present[ entry_role( $e ) ] = true;
	}
}
foreach ( array( 'slot_rename', 'rel_to_ref', 'related_src', 'size_fold', 'bare_url', 'base_chain', 'join_escape', 'slot_fold' ) as $role ) {
	assert_eq( "role found: {$role}", true, isset( $present[ $role ] ) );
}

// ===========================================================================
echo "\nO2 — the order each registration-block comment states\n";

// [ A, B, tags that MUST be among those checked, a phrase from the comment it pins ]
$pairs = array(
	array( 'size_fold', 'bare_url', array( 'image', 'term_image', 'try_image' ), 'REGISTERED AFTER THE FOLD' ),
	array( 'slot_rename', 'related_src', array( 'try_text', 'try_image' ), 'AFTER the try_ slot-key renames' ),
	array( 'related_src', 'slot_fold', array( 'try_text', 'try_image' ), 'BEFORE the fold entry (which consumes flat `N-src`' ),
	array( 'rel_to_ref', 'slot_fold', array( 'try_text', 'try_image' ), 'BEFORE the fold entry: `rel` is NOT in BWS_FOLD_FLAT_AXES' ),
	array( 'rel_to_ref', 'base_chain', array( 'text', 'image' ), 'AFTER every entry that PRODUCES a flat `src:ref`' ),
	array( 'related_src', 'base_chain', array( 'text', 'image' ), 'AFTER every entry that PRODUCES a flat `src:ref`' ),
	array( 'join_escape', 'slot_fold', array( 'join' ), 'BEFORE the fold entry, and that order is load-bearing' ),
);
$source = (string) file_get_contents( __DIR__ . '/../../includes/tags/deprecated-tags.php' );
foreach ( $pairs as [ $a, $b, $must_cover, $comment ] ) {
	$r = check_before( $by_tag, $a, $b );
	assert_eq( "{$a} < {$b}: the pinned comment is still in the source  [{$comment}]",
		true, false !== strpos( $source, $comment ) );
	assert_eq( "{$a} < {$b} is checked on " . implode( ', ', $must_cover ),
		array(),
		array_values( array_diff( $must_cover, $r['checked'] ) ) );
	assert_eq( "{$a} < {$b} holds on every tag that has both",
		array(), $r['violations'] );
}

// The `term` family's generated entries must come AFTER the pass above: the generator skips a
// name already claimed, so the other order lets it claim names the hand-written entries own.
$bootstrap = (string) file_get_contents( __DIR__ . '/../../bws-gb-dynamic-tags-extensions.php' );
$pass_at   = strpos( $bootstrap, 'bws_register_option_migrations();' );
$term_at   = strpos( $bootstrap, "bws_register_modifier_root_migrations( 'term'" );
assert_eq( 'bootstrap: the pinned comment is still in the source  [AFTER bws_register_option_migrations(), and the order is load-bearing]',
	true, false !== strpos( $bootstrap, 'AFTER bws_register_option_migrations(), and the order is load-bearing' ) );
assert_eq( 'bootstrap: both calls are found', true, false !== $pass_at && false !== $term_at );
assert_eq( 'bootstrap: the term-family generator is called after the option-migration pass', true, $pass_at < $term_at );

// "LAST, deliberately": nothing registers after a tag's slot-fold entry.
$last = check_last( $by_tag, 'slot_fold' );
assert_eq( 'slot fold: the pinned comment is still in the source  [LAST, deliberately]',
	true, false !== strpos( $source, 'LAST, deliberately' ) );
assert_eq( 'slot fold is checked on join, try_text and try_image',
	array(), array_values( array_diff( array( 'join', 'try_text', 'try_image' ), $last['checked'] ) ) );
assert_eq( 'slot fold is the last entry of every tag that has one', array(), $last['violations'] );

// ===========================================================================
echo "\nO3 — the checker rejects a reversed list (it is not vacuous)\n";

$entry = static function ( string $callback ): array {
	return array( 'type' => 'option', 'match_tag' => 'image', 'transform_callback' => $callback );
};
$forward  = array( 'image' => array( $entry( 'bws_migrate_image_as_size_fold' ), $entry( 'bws_migrate_image_as_bare_url' ) ) );
$reversed = array( 'image' => array_reverse( $forward['image'] ) );
assert_eq( 'forward list: no violation',
	array( 'checked' => array( 'image' ), 'violations' => array() ),
	check_before( $forward, 'size_fold', 'bare_url' ) );
assert_eq( 'reversed list: the tag is named as the violation',
	array( 'checked' => array( 'image' ), 'violations' => array( 'image' ) ),
	check_before( $reversed, 'size_fold', 'bare_url' ) );
assert_eq( 'a tag missing one role is skipped, not passed',
	array( 'checked' => array(), 'violations' => array() ),
	check_before( array( 'image' => array( $entry( 'bws_migrate_image_as_size_fold' ) ) ), 'size_fold', 'bare_url' ) );

$with_tail = array( 'image' => array( $entry( 'bws_migrate_src_chain_slots' ), $entry( 'bws_migrate_image_as_bare_url' ) ) );
assert_eq( 'a role followed by another entry is named as not last',
	array( 'checked' => array( 'image' ), 'violations' => array( 'image' ) ),
	check_last( $with_tail, 'slot_fold' ) );
assert_eq( 'a role that is last passes',
	array( 'checked' => array( 'image' ), 'violations' => array() ),
	check_last( array( 'image' => array_reverse( $with_tail['image'] ) ), 'slot_fold' ) );

echo "\n";
if ( $failures ) {
	echo "FAILED: {$failures}/{$count}\n";
	exit( 1 );
}
echo "PASSED: {$count}/{$count}\n";
exit( 0 );
