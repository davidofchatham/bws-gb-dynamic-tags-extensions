<?php
/**
 * Standalone harness for the REGISTRATION ORDER of the option migrations.
 *
 * The sequence `bws_register_option_migrations()` registers in is a program (why:
 * MigrationRegistry::apply_option_migration()'s docblock). The order is stated in comments
 * beside each registration block in includes/tags/deprecated-tags.php; THIS file is what
 * fails when one of those statements stops being true. Each pair below names the comment
 * it pins by a phrase, and §O2 asserts that phrase is still in the source, so a reworded
 * comment fails here instead of drifting from its pin.
 *
 * Loads the REAL files and the REAL registration pass, and reads the order back through
 * MigrationRegistry::get_option_migrations_by_tag() (the grouping the scan and the run both
 * walk). Two things it deliberately does NOT do:
 *   - assert behavior: the per-transform harnesses (as-size-fold-test.php, fold-migration-test.php,
 *     related-post-src-migration-test.php) own what each entry DOES; this owns only where it sits.
 *     as-size-fold-test.php §A5 also pins the first pair below, through the engine; it is
 *     listed here as well so the whole set of pairs reads in one place.
 *   - assert across tags: an entry's neighbours are the entries of its OWN tag.
 *
 * VACUITY GUARD. Several registration blocks are `function_exists()`-guarded, so a harness
 * that forgot to load a file would find those entries absent and every pair involving them
 * would pass by having nothing to compare. Each role must therefore be found at all (§O1),
 * each pair must be checked on its named tags (§O2), and the checker itself is shown to
 * reject a reversed list (§O3).
 *
 * The `term` family's modifier → base entries are generated by
 * bws_register_modifier_root_migrations() in the plugin bootstrap, not in this pass. Its
 * position against this pass is pinned in §O2 as source order in the bootstrap file, the
 * one place it can be read, since running the bootstrap needs WordPress.
 *
 * Run:  php tools/test/migration-order-test.php   (exit 0 = pass, 1 = fail)
 *
 * @package BWS_Dynamic_Tags
 */

